        F(0xE8, 0x0D); F(0xE9, 0x4B); F(0xEA, 0x03); V(0xEB);
        V(0xEC); V(0xED); F(0xEE, 0x0A); F(0xEF, 0x15);
        V(0xF0); F(0xF1, 0x09); F(0xF2, 0x19); F(0xF3, 0x1A);
        V(0xF4); F(0xF5, 0x15); V(0xF6); V(0xF7);
        F(0xF8, 0x6A); V(0xF9); V(0xFA); V(0xFB);
        V(0xFC); V(0xFD); V(0xFF);
        // 0xFE has no known definition in either source table - left as 0 ("can't frame, give up").

        return t;
    }
}
