        V(0xCC); F(0xCD, 0x01); V(0xCE); F(0xCF, 0x4E);
        V(0xD0); F(0xD1, 0x02); F(0xD2, 0x19); V(0xD3);
        V(0xD4); V(0xD5); V(0xD6); V(0xD7);
        V(0xD8); F(0xD9, 0x10C); V(0xDA); V(0xDB);
        F(0xDC, 0x09); V(0xDD); V(0xDE); V(0xDF);
        V(0xE0); V(0xE1); F(0xE2, 0x0A); V(0xE3);
