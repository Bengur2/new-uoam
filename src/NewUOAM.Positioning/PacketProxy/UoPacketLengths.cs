namespace NewUOAM.Positioning.PacketProxy;

/// <summary>
/// Fixed length (in bytes, including the 1-byte packet ID) for every UO packet ID, or -1 for a
/// variable-length packet (ID byte followed by a big-endian ushort giving the TOTAL packet
/// length, including the ID and length bytes themselves).
///
/// Cross-checked between two independent, authoritative, open-source implementations that both
/// have to get this exactly right to function at all: ServUO's server-side packet writers
/// (Server/Network/Packets.cs) and ClassicUO's client-side PacketsTable.cs. Every ID this proxy
/// actually cares about (0x1B, 0x02, 0x20, 0x21, 0x22, 0x8C) matched exactly between the two.
/// </summary>
public static class UoPacketLengths
{
    public const byte EnterWorld = 0x1B;
    public const byte MovementRequest = 0x02;
    public const byte MobileUpdate = 0x20; // aka "teleport" / forced absolute position
    public const byte MovementReject = 0x21;
    public const byte MovementAck = 0x22;
    public const byte SelectServer = 0xA0; // client -> login server
    public const byte PlayServerRedirect = 0x8C; // login server -> client

    /// <summary>Index = packet ID. Value = fixed length, or -1 for variable-length.</summary>
    public static readonly int[] Lengths = BuildTable();

    private static int[] BuildTable()
    {
        var t = new int[256];
        Array.Fill(t, -1); // default: treat anything not explicitly listed as variable-length...
        // ...except that's wrong for genuinely-unknown IDs with no length prefix meaning either.
        // Mark everything unknown as 0 (= "cannot frame, give up") and only set real values below.
        Array.Fill(t, 0);

        void F(int id, int len) => t[id] = len; // fixed length
        void V(int id) => t[id] = -1; // variable length (2-byte length prefix follows the ID)

        F(0x00, 0x68); F(0x01, 0x05); F(0x02, 0x07); V(0x03);
        F(0x04, 0x02); F(0x05, 0x05); F(0x06, 0x05); F(0x07, 0x07);
        F(0x08, 0x0E); F(0x09, 0x05); F(0x0A, 0x0B); F(0x0B, 0x10A);
        V(0x0C); F(0x0D, 0x03); V(0x0E); F(0x0F, 0x3D);
        F(0x10, 0xD7); V(0x11); V(0x12); F(0x13, 0x0A);
        F(0x14, 0x06); F(0x15, 0x09); F(0x16, 0x01); V(0x17);
        V(0x18); V(0x19); V(0x1A); F(0x1B, 0x25);
        V(0x1C); F(0x1D, 0x05); F(0x1E, 0x04); F(0x1F, 0x08);
        F(0x20, 0x13); F(0x21, 0x08); F(0x22, 0x03); F(0x23, 0x1A);
        F(0x24, 0x07); F(0x25, 0x14); F(0x26, 0x05); F(0x27, 0x02);
        F(0x28, 0x05); F(0x29, 0x01); F(0x2A, 0x05); F(0x2B, 0x02);
        F(0x2C, 0x02); F(0x2D, 0x11); F(0x2E, 0x0F); F(0x2F, 0x0A);
        F(0x30, 0x05); F(0x31, 0x01); F(0x32, 0x02); F(0x33, 0x02);
        F(0x34, 0x0A); F(0x35, 0x28D); V(0x36); F(0x37, 0x08);
        F(0x38, 0x07); F(0x39, 0x09); V(0x3A); V(0x3B);
        V(0x3C); F(0x3D, 0x02); F(0x3E, 0x25); V(0x3F);
        F(0x40, 0xC9); V(0x41); V(0x42); F(0x43, 0x229);
        F(0x44, 0x2C9); F(0x45, 0x05); V(0x46); F(0x47, 0x0B);
        F(0x48, 0x49); F(0x49, 0x5D); F(0x4A, 0x05); F(0x4B, 0x09);
        V(0x4C); V(0x4D); F(0x4E, 0x06); F(0x4F, 0x02);
        V(0x50); V(0x51); V(0x52); F(0x53, 0x02);
        F(0x54, 0x0C); F(0x55, 0x01); F(0x56, 0x0B); F(0x57, 0x6E);
